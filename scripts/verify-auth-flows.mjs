import { readFileSync } from "node:fs";
import { join } from "node:path";
import { createClient } from "@supabase/supabase-js";

loadLocalEnv(".env.local");
loadLocalEnv(".env");

const config = {
  key: process.env.VITE_SUPABASE_PUBLISHABLE_KEY?.trim(),
  url: process.env.VITE_SUPABASE_URL?.trim(),
};

const testEmail = process.env.DEEPSPEC_AUTH_TEST_EMAIL?.trim();
const testPassword = process.env.DEEPSPEC_AUTH_TEST_PASSWORD?.trim();
const testOtpCode = process.env.DEEPSPEC_AUTH_TEST_EMAIL_CODE?.trim();
const shouldSendOtp = process.env.DEEPSPEC_AUTH_SEND_CODE === "true";
const requireCredentials = process.env.DEEPSPEC_AUTH_REQUIRE_CREDENTIALS === "true";

if (!config.url || !config.key) {
  fail(
    [
      "Auth verification blocked.",
      "Missing VITE_SUPABASE_URL or VITE_SUPABASE_PUBLISHABLE_KEY in .env.local.",
      "Use the Supabase publishable/anon key, not a service-role key.",
    ].join("\n"),
  );
}

try {
  console.log("[0/6] Checking Supabase Auth settings endpoint...");
  const settings = await fetchAuthSettings(config);
  assert(settings.disable_signup !== true, "Supabase signup is disabled.");
  console.log("      Signup is enabled.");

  console.log("[1/6] Checking Google and GitHub OAuth providers...");
  assert(settings.external?.google === true, "Google provider is not enabled in Supabase Auth settings.");
  assert(settings.external?.github === true, "GitHub provider is not enabled in Supabase Auth settings.");
  console.log("      Google and GitHub providers are enabled.");

  const supabase = createClient(config.url, config.key, {
    auth: {
      autoRefreshToken: false,
      detectSessionInUrl: false,
      persistSession: false,
    },
  });

  console.log("[2/6] Generating OAuth redirect URLs without opening a browser...");
  await assertOAuthUrl(supabase, "google");
  await assertOAuthUrl(supabase, "github");
  console.log("      Google and GitHub OAuth redirects are generated by Supabase.");

  console.log("[3/6] Checking email/password live credentials...");
  if (testEmail && testPassword) {
    await assertPasswordSignIn(supabase, testEmail, testPassword);
    console.log("      Email/password sign-in verified with a real Supabase session.");
  } else if (requireCredentials) {
    throw new Error("Set DEEPSPEC_AUTH_TEST_EMAIL and DEEPSPEC_AUTH_TEST_PASSWORD to verify live password login.");
  } else {
    console.log("      Skipped. Set DEEPSPEC_AUTH_TEST_EMAIL and DEEPSPEC_AUTH_TEST_PASSWORD for a live password check.");
  }

  console.log("[4/6] Checking verification-code flow...");
  if (testEmail && shouldSendOtp) {
    await assertOtpRequest(supabase, testEmail);
    console.log("      Verification code request sent. Check the inbox for the Supabase code.");
  } else {
    console.log("      Code send skipped. Set DEEPSPEC_AUTH_SEND_CODE=true and DEEPSPEC_AUTH_TEST_EMAIL to send one.");
  }

  if (testEmail && testOtpCode) {
    await assertOtpVerification(supabase, testEmail, testOtpCode);
    console.log("      Verification code accepted and returned a real Supabase session.");
  } else if (requireCredentials) {
    throw new Error("Set DEEPSPEC_AUTH_TEST_EMAIL_CODE after receiving an email code to verify code login end to end.");
  } else {
    console.log("      Code entry skipped. Set DEEPSPEC_AUTH_TEST_EMAIL_CODE after receiving the code.");
  }

  console.log("[5/6] Auth verification completed.");
} catch (error) {
  fail(error instanceof Error ? error.message : "Unknown auth verification failure.");
}

async function fetchAuthSettings({ key, url }) {
  const response = await fetch(`${url.replace(/\/$/, "")}/auth/v1/settings`, {
    headers: { apikey: key },
  });
  const body = await response.json().catch(() => null);

  if (!response.ok || !body) {
    throw new Error(`Could not read Supabase Auth settings. HTTP ${response.status}.`);
  }

  return body;
}

async function assertOAuthUrl(supabase, provider) {
  const { data, error } = await supabase.auth.signInWithOAuth({
    provider,
    options: {
      redirectTo: "http://127.0.0.1:5173/scan",
      skipBrowserRedirect: true,
    },
  });

  if (error) {
    throw new Error(`${provider} OAuth URL generation failed: ${error.message}`);
  }

  assert(typeof data.url === "string" && data.url.includes("/auth/v1/authorize"), `${provider} OAuth URL was not returned.`);
}

async function assertPasswordSignIn(supabase, email, password) {
  const { data, error } = await supabase.auth.signInWithPassword({ email, password });
  if (error) {
    throw new Error(`Password sign-in failed: ${error.message}`);
  }

  assert(Boolean(data.user?.id), "Password sign-in did not return a user.");
  assert(Boolean(data.session?.access_token), "Password sign-in did not return a session token.");
  await supabase.auth.signOut();
}

async function assertOtpRequest(supabase, email) {
  const { error } = await supabase.auth.signInWithOtp({
    email,
    options: {
      shouldCreateUser: true,
    },
  });

  if (error) {
    throw new Error(`Verification code request failed: ${error.message}`);
  }
}

async function assertOtpVerification(supabase, email, token) {
  const { data, error } = await supabase.auth.verifyOtp({
    email,
    token,
    type: "email",
  });

  if (error) {
    throw new Error(`Verification code entry failed: ${error.message}`);
  }

  assert(Boolean(data.user?.id), "Verification code did not return a user.");
  assert(Boolean(data.session?.access_token), "Verification code did not return a session token.");
  await supabase.auth.signOut();
}

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function loadLocalEnv(filename) {
  const path = join(process.cwd(), filename);
  let contents;

  try {
    contents = readFileSync(path, "utf8");
  } catch {
    return;
  }

  for (const line of contents.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;

    const separatorIndex = trimmed.indexOf("=");
    if (separatorIndex === -1) continue;

    const key = trimmed.slice(0, separatorIndex).trim();
    const rawValue = trimmed.slice(separatorIndex + 1).trim();
    if (!key || process.env[key]) continue;

    process.env[key] = rawValue.replace(/^["']|["']$/g, "");
  }
}

function fail(message) {
  console.error(message);
  process.exitCode = 1;
}
